from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Literal

from pydantic import Field

from pipecheckkk_ai.models import ApiModel


class DefectType(StrEnum):
    CRACK = "CRACK"
    DEBRIS = "DEBRIS"
    ROOT = "ROOT"
    BLOCKAGE = "BLOCKAGE"
    SURFACE_DAMAGE = "SURFACE_DAMAGE"
    OTHER = "OTHER"


class Severity(StrEnum):
    CRITICAL = "CRITICAL"
    WARNING = "WARNING"
    NORMAL = "NORMAL"


DEFECT_TYPE_LABELS: dict[DefectType, str] = {
    DefectType.CRACK: "균열",
    DefectType.DEBRIS: "퇴적물",
    DefectType.ROOT: "뿌리 침투",
    DefectType.BLOCKAGE: "막힘",
    DefectType.SURFACE_DAMAGE: "표면 손상",
    DefectType.OTHER: "기타 결함",
}

SEVERITY_LABELS: dict[Severity, str] = {
    Severity.CRITICAL: "심각",
    Severity.WARNING: "주의",
    Severity.NORMAL: "경미",
}


class DefectFact(ApiModel):
    """One defect, reduced to the fields that are safe to place in a prompt."""

    defect_id: int | None = None
    defect_type: DefectType
    severity: Severity
    confidence: float = Field(ge=0.0, le=1.0)
    position_m: float = Field(ge=0.0, le=10000.0)
    blockage_ratio: float | None = Field(default=None, ge=0.0, le=1.0)
    snapshot_path: str | None = None


class SessionFacts(ApiModel):
    """Application-owned facts describing one inspection session."""

    session_id: int
    district_id: int
    mode: str
    status: str
    started_at: datetime | None = None
    ended_at: datetime | None = None
    duration_seconds: int | None = Field(default=None, ge=0)
    defects: list[DefectFact] = Field(default_factory=list)
    dropped_defect_count: int = Field(default=0, ge=0)

    @property
    def defect_total(self) -> int:
        return len(self.defects) + self.dropped_defect_count

    def count_by_severity(self, severity: Severity) -> int:
        return sum(1 for defect in self.defects if defect.severity is severity)


class StateGrades(ApiModel):
    """구조적 / 운영적 상태등급. Computed in code — never generated by the model."""

    structural: int = Field(ge=0, le=5)
    operational: int = Field(ge=0, le=5)


class ReportNarrative(ApiModel):
    """The session-level prose the language model is allowed to author."""

    assessment: str
    recommendations: list[str] = Field(default_factory=list)


class ObservationFailure(StrEnum):
    """Why a snapshot was not read. Surfaced in the report for debugging."""

    NO_SNAPSHOT = "NO_SNAPSHOT"
    MODEL_UNAVAILABLE = "MODEL_UNAVAILABLE"
    BUDGET_EXCEEDED = "BUDGET_EXCEEDED"
    IMAGE_FETCH_FAILED = "IMAGE_FETCH_FAILED"
    VALIDATION_REJECTED = "VALIDATION_REJECTED"
    INFERENCE_FAILED = "INFERENCE_FAILED"


FAILURE_LABELS: dict[ObservationFailure, str] = {
    ObservationFailure.NO_SNAPSHOT: "결함 사진 미등록",
    ObservationFailure.MODEL_UNAVAILABLE: "판독 모델 미로드",
    ObservationFailure.BUDGET_EXCEEDED: "사진 판독 건수 제한 초과",
    ObservationFailure.IMAGE_FETCH_FAILED: "결함 사진 내려받기 실패",
    ObservationFailure.VALIDATION_REJECTED: "판독 결과 검증 실패",
    ObservationFailure.INFERENCE_FAILED: "판독 모델 실행 오류",
}


class DefectObservation(ApiModel):
    """A per-defect finding, optionally written from the snapshot image.

    `source` records how the text was produced so a reviewer can tell an
    image-derived observation from a metadata-only one. When `source` is
    `metadata`, `failure_code` says why the image was not read.
    """

    defect_id: int | None = None
    position_m: float = Field(ge=0.0, le=10000.0)
    defect_type: DefectType
    severity: Severity
    image_url: str | None = None
    description: str
    source: Literal["vision", "metadata"]
    failure_code: ObservationFailure | None = None
    failure_detail: str | None = None


class ReportSummary(ApiModel):
    session_id: int
    assessment: str
    recommendations: list[str] = Field(default_factory=list)
    observations: list[DefectObservation] = Field(default_factory=list)
    grades: StateGrades
    defect_total: int = Field(ge=0)
    critical_count: int = Field(ge=0)
    warning_count: int = Field(ge=0)
    dropped_defect_count: int = Field(default=0, ge=0)
    vision_described_count: int = Field(default=0, ge=0)
    generated_at: datetime
    latency_ms: float = Field(ge=0.0)
    source_model: str
    status: Literal["ready", "fallback"]
